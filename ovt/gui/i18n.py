class I18n:
    def __init__(self, lang="ar"):
        self.lang = lang if lang in ("ar", "en") else "ar"

    @property
    def rtl(self) -> bool:
        return self.lang == "ar"

    def t(self, key: str) -> str:
        v = S.get(key)
        if not v:
            return key
        return v[0] if self.lang == "ar" else v[1]


